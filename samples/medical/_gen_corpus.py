def render_scanned_report(out: Path) -> None:
    """文字排版渲染成高分辨率图像页，转成无文字层的"扫描件"PDF。

    真实扫描件 = 拍照/扫描生成的光栅图，本脚本用 Pillow 以 WenQuanYi 黑体
    把同一批内容画到 A4 白底页上再导出 PDF，模拟最常见的扫描件形态。
    """
    from PIL import Image, ImageDraw, ImageFont

    dpi = 200  # 200 DPI 足够 OCR；太低会糊字
    width, height = int(8.27 * dpi), int(11.69 * dpi)
    img = Image.new("RGB", (width, height), "white")
    draw = ImageDraw.Draw(img)
    margin_x = int(0.9 * dpi)
    avail = width - 2 * margin_x

    font_title = ImageFont.truetype(FONT, 52)
    font_body = ImageFont.truetype(FONT, 40)
    y = int(1.1 * dpi)

    def draw_line(text: str, font, gap: int = 10, size: int = 40) -> None:
        nonlocal y
        cur = ""
        for ch in text:
            if cur and draw.textlength(cur + ch, font=font) > avail:
                draw.text((margin_x, y), cur, font=font, fill=(25, 25, 25))
                y += int(size * 1.7)
                cur = ch
            else:
                cur += ch
        if cur:
            draw.text((margin_x, y), cur, font=font, fill=(25, 25, 25))
            y += int(size * 1.7)
        y += gap

    for line in SCAN_REPORT_LINES:
        if line == "---":
            y += 8
            draw.line([(margin_x, y), (width - margin_x, y)], fill=(150, 150, 150), width=2)
            y += 8 + 14
            continue
        if line.startswith("清源生物制药"):
            draw_line(line, font_title, size=52)
        elif line.startswith("检验项目与结果") or line.startswith("检验结论"):
            draw_line(line, font_body, size=40)
        else:
            draw_line(line, font_body, size=40)
    img.convert("RGB").save(str(out), "PDF", resolution=dpi)


