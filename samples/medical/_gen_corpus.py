def render_pdf(out: Path, lines: list[str]) -> None:
    pdf = FPDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_font("wqy", "", FONT)
    pdf.add_page()
    pdf.set_font("wqy", "", 11)
    pdf.set_left_margin(20)
    pdf.set_right_margin(20)
    first_title = True
    for line in lines:
        pdf.set_x(20)  # fpdf2 multi_cell 不重置 x，须显式回到左边界
        if line == "---":
            pdf.ln(3)
            continue
        if line == "###PAGE###":
            pdf.add_page()
            continue
        if line == "###TABLE_WS###":
            _draw_table(pdf)
            pdf.ln(3)
            continue
        if first_title:
            pdf.set_font("wqy", "", 11)
            pdf.cell(0, 7, line)
            pdf.ln(7)
            first_title = False
            continue
        # 以数字开头的节标题用稍大字号，其余正文
        if line and line[0].isdigit():
            pdf.set_font("wqy", "", 12)
            pdf.multi_cell(0, 6.5, line)
            pdf.set_font("wqy", "", 11)
        else:
            pdf.multi_cell(0, 6, line)
    out.write_bytes(pdf.output())


def _draw_table(pdf: FPDF) -> None:
    pdf.set_font("wqy", "", 10)
    widths = (45, 55, 70)
    for row in TABLE_WS_ROWS:
        for w, cell in zip(widths, row):
            pdf.cell(w, 8, cell, border=1)
        pdf.ln(8)
    pdf.set_font("wqy", "", 11)


